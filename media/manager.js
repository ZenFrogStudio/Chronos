  /**
   * A VS Code-style sash. Pointer capture is what makes the drag survive the
   * pointer leaving the 6px strip — without it, moving faster than the layout
   * repaints drops the drag.
   *
   * Measured from the shell's left edge and the Runs panel's own bottom edge, so
   * the banner and notice rows above cannot skew the maths.
   */
  function startSash(e, axis) {
    const sash = /** @type {HTMLElement} */ (e.currentTarget);
    e.preventDefault();
    sash.setPointerCapture(e.pointerId);
    sash.classList.add('is-active');
    document.body.classList.add('is-resizing');
    document.body.style.cursor = axis === 'x' ? 'col-resize' : 'row-resize';

    const move = (ev) => {
      if (axis === 'x') {
        libraryWidth = clampLibrary(ev.clientX - shellEl.getBoundingClientRect().left);
      } else {
        activityHeight = clampActivity(activityEl.getBoundingClientRect().bottom - ev.clientY);
      }
      applySizes();
    };

    const end = () => {
      sash.removeEventListener('pointermove', move);
      sash.removeEventListener('pointerup', end);
      sash.removeEventListener('lostpointercapture', end);
      sash.classList.remove('is-active');
      document.body.classList.remove('is-resizing');
      document.body.style.cursor = '';
      saveViewState();
    };

    sash.addEventListener('pointermove', move);
    sash.addEventListener('pointerup', end);
    sash.addEventListener('lostpointercapture', end);
  }

  librarySashEl.addEventListener('pointerdown', (e) => startSash(e, 'x'));
  activitySashEl.addEventListener('pointerdown', (e) => startSash(e, 'y'));

