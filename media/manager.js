  detailEl.addEventListener('change', (e) => {
    const el = /** @type {HTMLInputElement|HTMLSelectElement} */ (e.target);

    // Before the guards below, which are about a plan and would swallow every
    // settings edit. On change only, never on input: a text field must not
    // rewrite settings.json on every keystroke.
    if (el.dataset && el.dataset.setting) {
      // An emptied number box is not a value — `Number('')` is 0, which would
      // silently write the field's minimum. NaN is refused by the host instead,
      // and the refusal is what snaps the control back to what is stored.
      const value =
        el.type === 'checkbox'
          ? /** @type {HTMLInputElement} */ (el).checked
          : el.type === 'number'
            ? (el.value === '' ? Number.NaN : Number(el.value))
            : el.value;
      return send({ type: 'updateSetting', key: el.dataset.setting, value });
    }

    const field = el.dataset ? el.dataset.field : undefined;
    if (!field || field === 'editor') return;

    const series = seriesForPlan(planByName(selected));
    if (!series) return;

    // The three time dropdowns are one value between them, so any of them
    // changing reads all three. The date is whatever the series already runs on.
    if (field === 'pickerHour' || field === 'pickerMinute' || field === 'pickerAmpm') {
      const read = (name) =>
        /** @type {HTMLSelectElement} */ (detailEl.querySelector(`[data-field="${name}"]`)).value;
      const at = new Date(series.nextRunAt);
      const hour = from12(Number(read('pickerHour')), read('pickerAmpm'));
      const local = localStr(at.getFullYear(), at.getMonth(), at.getDate(), hour, Number(read('pickerMinute')));
      return patch(series.id, whenPatch(series, toUtcIso(local)));
    }

    if (field === 'repeat') {
      const timeLocal = localTimeOf(series.nextRunAt);
      if (el.value === 'once') return patch(series.id, { recurrence: null });
      if (el.value === 'daily') {
        return patch(series.id, { recurrence: { daysOfWeek: [0, 1, 2, 3, 4, 5, 6], timeLocal } });
      }
      // Monthly takes its day from the When field, the way weekly takes its
      // weekday — so there is no second picker to keep in step with it.
      if (el.value === 'monthly') {
        return patch(series.id, {
          recurrence: { daysOfWeek: [], timeLocal, dayOfMonth: new Date(series.nextRunAt).getDate() }
        });
      }
      return patch(series.id, {
        recurrence: { daysOfWeek: [new Date(series.nextRunAt).getDay()], timeLocal }
      });
    }

    if (field === 'permissionMode') return patch(series.id, { permissionMode: el.value });

    // A model id belongs to one engine, so switching engines drops one the new
    // engine has never heard of rather than passing it on to fail at fire time.
    if (field === 'agent') {
      const next = state.agents.find((a) => a.id === el.value);
      const keeps = !!next && next.models.some((m) => m.value === (series.model || ''));
      customModel = false;
      return patch(series.id, { agent: el.value, model: keeps ? series.model : undefined });
    }

    if (field === 'model') {
      // Custom… is a UI state, not a value: it reveals the box below, and the
      // box is what patches.
      if (el.value === CUSTOM_MODEL) {
        customModel = true;
        return render();
      }
      customModel = false;
      return patch(series.id, { model: el.value || undefined });
    }

    if (field === 'customModel') return patch(series.id, { model: el.value.trim() || undefined });
  });

